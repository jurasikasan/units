// Ulaw decodes one µ-law byte to a 16-bit linear sample.
func Ulaw(c byte) int16 { return ulawToLinear[c] }

// Alaw decodes one A-law byte to a 16-bit linear sample, using the
// ITU-T G.711 (G.721) algorithm. It satisfies the reference anchors
// 0xD5 -> 8 and 0x55 -> -8.
func Alaw(c byte) int16 {
	ix := int(c) ^ 0x55
	iexp := (ix >> 4) & 0x07
	mant := ix & 0x0F
	if iexp > 0 {
		mant += 16
	}
	mant = (mant << 4) + 8
	if iexp > 1 {
		mant <<= iexp - 1
	}
	if c <= 0x7F {
		return -int16(mant)
	}
	return int16(mant)
}
